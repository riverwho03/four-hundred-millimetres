  const load = () => { try { return localStorage.getItem(STORE); } catch (e) { return null; } };
  const save = l => { try { localStorage.setItem(STORE, l); } catch (e) { /* storage can be blocked */ } };
  function detect() {
    const saved = load();
    if (saved === 'en' || saved === 'zh') return saved;
    return /^zh/i.test(navigator.language || '') ? 'zh' : 'en';
  }

  let lang = detect();
  const listeners = [];

  function t(key, vars) {
    let s = STR[lang] && STR[lang][key];
    if (s === undefined) s = STR.en[key];
    if (s === undefined) return key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
  }
  // For data objects with English fields and an optional zh: { ... } block.
  const pick = (obj, field) => (lang === 'zh' && obj.zh && obj.zh[field]) || obj[field];

  function apply() {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-i18n]').forEach(e => {
      const text = t(e.dataset.i18n);
      if (e.tagName === 'TITLE') document.title = text; else e.textContent = text;
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(e => {
      e.dataset.i18nAttr.split(';').forEach(pair => {
        const [attr, key] = pair.split(':');
        if (attr && key) e.setAttribute(attr.trim(), t(key.trim()));
      });
    });
  }

  function setLang(next) {
    if ((next !== 'en' && next !== 'zh') || next === lang) return;
    lang = next;
    save(next);
    apply();
    listeners.slice().forEach(fn => fn(lang));
  }

  window.I18N = { t, pick, apply, setLang, onChange: fn => { listeners.push(fn); }, get lang() { return lang; } };
  apply();
